def rel(path) = path.to_s.sub("#{ROOT}/", "")

# Runs argv (no shell), logs it, returns [stdout, stderr, status].
def run(*argv, env: {}, stdin: nil, chdir: ROOT)
  LOG.puts((env.map { |k, v| "#{k}=#{rel(v)}" } + argv.map { |a| rel(a) }).join(" "))
  out, err, st = Open3.capture3(env, *argv.map(&:to_s), stdin_data: stdin.to_s, chdir: chdir)
  [out, err, st]
end

def run!(*argv, **kw)
  out, err, st = run(*argv, **kw)
  abort "FAILED (#{st.exitstatus}): #{argv.join(' ')}\n#{err}" unless st.success?
  [out, err]
end

def write(name, text)
  File.write(File.join(GEN, name), text)
  name
end

