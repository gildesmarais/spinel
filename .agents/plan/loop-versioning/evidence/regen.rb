# The Ruby loop in each binary: the loops of _sp_main_body (sp_matmul is
# inlined into it), as asm and as IR with value names kept.
def asm_and_ir(name, argv, cfile, tag, extra = [])
  s = File.join(BIN, "#{name}.#{tag}.s")
  ll = File.join(BIN, "#{name}.#{tag}.ll")
  run!(*cc_argv(argv, File.join(GEN, cfile), s, extra + ["-S"], compile_only: true).reject { |x| x == "-c" })
  run!(*cc_argv(argv, File.join(GEN, cfile), ll, extra + ["-S", "-emit-llvm", "-fno-discard-value-names"],
                compile_only: true).reject { |x| x == "-c" })
  asm = File.read(s)
  fn = asm[/^__sp_main_body:.*?(?=^\s*\.cfi_endproc)/m] or abort "no _sp_main_body in #{s}"
  ops = { "fmul.2d (vector)" => /^\tfmul\.2d\t/, "fadd.2d (vector)" => /^\tfadd\.2d\t/,
          "fmul dN (scalar)" => /^\tfmul\td\d/, "fadd dN (scalar)" => /^\tfadd\td\d/,
          "ldp qN (vector load)" => /^\tldp\tq\d/, "stp qN (vector store)" => /^\tstp\tq\d/,
          "calls to _sp_raise*" => /^\tbl\t_sp_raise/, "calls to _sp_FloatArray*" => /^\tbl\t_sp_FloatArray/ }
  counts = ops.transform_values { |re| fn.scan(re).size }
  ir = File.read(ll)
  irf = ir[/^define [^\n]*@_sp_main_body\(.*?^\}/m] or abort "no _sp_main_body in #{ll}"
  blocks = irf.scan(/^([\w.]+):/).flatten
  write("#{name}.#{tag}.main_body.s", fn)
  [counts, blocks, irf]
end

