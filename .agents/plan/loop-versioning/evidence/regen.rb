# The cc argv spinel uses, captured through the wrapper; the C it compiled,
# with its #line directives dropped, must be the C `-S --no-line-map` prints.
def capture_build(name, src)
  log = File.join(BIN, "#{name}.ccargs")
  run!(SPINEL, src, "--cc=#{CCWRAP}", "-o", File.join(BIN, "#{name}.spinel"), env: { "CCWRAP_LOG" => log })
  argv = File.read(log).lines.map(&:chomp)
  emitted = run!(SPINEL, src, "-S", "--no-line-map")[0]
  compiled = File.read("#{log}.c").lines.reject { |l| l.start_with?("#line ") }.join
  [argv, emitted, compiled == emitted]
end

# argv with the source replaced, the output renamed, and extra flags added
def cc_argv(argv, src, out, extra = [], compile_only: false)
  a = argv.dup
  i = a.index { |x| x.end_with?(".c") } or abort "no .c in cc argv"
  a[i] = src
  o = a.index("-o")
  a[o + 1] = out
  if compile_only
    a.reject! { |x| x.end_with?(".a") || x == "-lm" || x.start_with?("-Wl,") }
    a.insert(1, "-c")
  end
  ["cc", *a[0...i], *extra, *a[i..]]
end

