# Remarks for the emitted file's own lines, plus the optimisation record of
# the loop vectorizer by function (the record keeps the remarks whose
# location is an inlined header line, such as an inlined runtime helper's loop).
def remarks(name, argv, cfile, tag, extra = [])
  obj = File.join(BIN, "#{name}.#{tag}.o")
  yaml = File.join(BIN, "#{name}.#{tag}.opt.yaml")
  _, err, st = run(*cc_argv(argv, File.join(GEN, cfile), obj,
                            REMARKS + extra + ["-fsave-optimization-record", "-foptimization-record-file=#{yaml}",
                                               "-foptimization-record-passes=loop-vectorize"], compile_only: true))
  abort err unless st.success?
  own = err.lines.select { |l| l.include?("#{cfile}:") && l.include?("remark:") }
               .map { |l| l.sub("#{GEN}/", "") }
  recs = File.read(yaml).split(/^--- /).drop(1).map do |r|
    fn = r[/^Function:\s+(\S+)/, 1]
    loc = r[/^DebugLoc:\s+\{ File: '([^']+)', Line: (\d+)/] ? "#{Regexp.last_match(1).sub("#{GEN}/", '')}:#{Regexp.last_match(2)}" : "-"
    msg = r.scan(/^\s+- String:\s+'?(.*?)'?$/).flatten.join
    "#{r[/\A!(\w+)/, 1]}\t#{fn}\t#{loc}\t#{msg}"
  end
  write("#{name}.#{tag}.remarks.txt",
        "# cc #{(REMARKS + extra).join(' ')} on gen/#{cfile}\n# remarks located in gen/#{cfile}:\n" +
        (own.empty? ? "(none)\n" : own.join) +
        "\n# loop-vectorize optimisation record (kind, function, location, message):\n" + recs.join("\n") + "\n")
end

